def test_ned_to_body_convention():
    yaw_ned, vN, vE, yaw_rate = 0.0, 1.0, 0.2, -0.3
    psi = R.wrap_pi(math.pi / 2.0 - yaw_ned)
    u = vN * math.cos(yaw_ned) + vE * math.sin(yaw_ned)
    v = vN * math.sin(yaw_ned) - vE * math.cos(yaw_ned)
    r = -yaw_rate
    assert psi == pytest.approx(math.pi / 2.0)
    assert u == pytest.approx(1.0)
    assert v == pytest.approx(-0.2)
    assert r == pytest.approx(0.3)


def test_right_forward_is_positive_yaw_moment():
    d = 0.25
    q = np.array([[[0.0, 0.0, 1.0, 0.0]]])       # only right thruster forward
    tau = R.old.tau_from_q(q, [25.0, 0.0, 25.0, 0.0], d)[0, 0]
    assert tau[0] == pytest.approx(25.0)
    assert tau[2] == pytest.approx(25.0 * d)


