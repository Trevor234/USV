"""Regression tests for the 2026-11-18 MCAP re-identification pipeline.

Two certification paths only:

  1. time base: continuous FCU anchors across the 2**32 us servo wrap, a ROS
     log clock that steps backwards by 0.671 s, and a 2 s PWM gap -- no window
     may ever span the gap, and unwrapping must stay continuous.
  2. synthetic fit: numbers generated by the real ``simulate`` must be
     recovered to <2%, and perturbing the holdout observation must leave the
     fit and bootstrap untouched while changing replay error.

No production MCAP is read here.
"""
