# 3. synthetic identification round trip
# ---------------------------------------------------------------------------
TRUE = dict(Xu=-3.0, Xuu=-9.0, Nr=-4.0, Nrr=-1.4, G=27.0)


def _hydro(p_base):
    h = dict(p_base)
    h.update({'Xu': TRUE['Xu'], 'Xuu': TRUE['Xuu'], 'Nr': TRUE['Nr'],
              'Nrr': TRUE['Nrr']})
    return h


def _synthetic_windows(p_base, n=12, dt=R.DT):
    rng = np.random.default_rng(61118)
    hydro = _hydro(p_base)
    nu0 = rng.uniform([0.15, -0.20, -0.60], [1.25, 0.20, 0.60], (n, 3))
    pwm = rng.integers(1560, 1791, (n, 2)).astype(float)
    steps = int(round(R.WIN_S / dt))
    q = {0: R.old.pwm_to_normalized(pwm[:, 0], R.SERVO_MIN, R.SERVO_TRIM,
                                    R.SERVO_MAX, R.PWM_DEADZONE_US),
         1: R.old.pwm_to_normalized(pwm[:, 1], R.SERVO_MIN, R.SERVO_TRIM,
                                    R.SERVO_MAX, R.PWM_DEADZONE_US)}
    pl, _nl = R.old.direction_split(q[0])
    pr, _nr = R.old.direction_split(q[1])
    q4 = np.stack([pl, np.zeros_like(pl), pr, np.zeros_like(pr)], axis=-1)
    tau = R.old.tau_from_q(q4, [TRUE['G'], 0.0, TRUE['G'], 0.0], p_base['d_thruster'])
    tau_seq = np.repeat(tau[:, None, :], steps, axis=1)
    x0 = np.column_stack([np.zeros(n), np.zeros(n), np.zeros(n), nu0])
    sim = R.old.simulate(x0, tau_seq, hydro, dt=dt)
    t = dt * np.arange(steps + 1)
    wins = []
    for i in range(n):
        snap_t = np.linspace(t[0], t[-1], 5)
        snap_l = np.full(snap_t.shape, pwm[i, 0])
        snap_r = np.full(snap_t.shape, pwm[i, 1])
        w = {'id': f'S{i:02d}', 'stage': 'train_B', 'cluster': i // 4,
             't_nodes': t.copy(), 'snap_t': snap_t,
             'snap_l': snap_l, 'snap_r': snap_r,
             'u': sim[i, :, 3].copy(), 'v': sim[i, :, 4].copy(),
             'r': sim[i, :, 5].copy(),
             'x': sim[i, :, 0].copy(), 'y': sim[i, :, 1].copy(),
             'psi': sim[i, :, 2].copy(),
             'x0': 0.0, 'y0': 0.0, 'psi0': 0.0,
             'u_p50': float(np.median(sim[i, :, 3])),
             'r_max_abs': float(np.max(np.abs(sim[i, :, 5]))),
             'IQ_sum': 0.0, 'IQ_diff': 0.0}
        IQ_sum, IQ_diff = R.input_terms(t, snap_t, snap_l, snap_r, mode='zoh')
        m = R.old.hydro_matrix(p_base)
        w['surge'], w['yaw'] = R.window_row(t, w['u'], w['v'], w['r'], m,
                                            IQ_sum, IQ_diff, p_base)
        w['IQ_sum'], w['IQ_diff'] = IQ_sum, IQ_diff
        wins.append(w)
    return wins, pwm, steps, t


def test_synthetic_parameters_recovered_within_2pct():
    p_base = R.old.load_baseline(os.path.join(
        os.path.dirname(os.path.dirname(os.path.dirname(HERE))),
        'usv_mpc_ws/src/usv_bringup/config/usv_params_B.yaml'))
    wins, _pwm, _steps, _t = _synthetic_windows(p_base)
    spec = dict(R.STRUCTURES['M1'])
    spec['name'] = 'M1'
    x, info = R.fit_structure(wins, spec, p_base)
    assert x is not None, info
    assert info['supported'], info
    got = dict(zip(spec['cols'], x))
    want = {'a1': -TRUE['Xu'], 'a2': -TRUE['Xuu'], 'n1': -TRUE['Nr'],
            'n2': -TRUE['Nrr'], 'G': TRUE['G']}
    for k, v in want.items():
        assert abs(got[k] - v) / abs(v) < 0.02, (k, got[k], v)


def test_holdout_perturbation_does_not_move_fit_but_moves_replay():
    p_base = R.old.load_baseline(os.path.join(
        os.path.dirname(os.path.dirname(os.path.dirname(HERE))),
        'usv_mpc_ws/src/usv_bringup/config/usv_params_B.yaml'))
    wins, _pwm, _steps, _t = _synthetic_windows(p_base)
    train, hold = wins[:8], wins[8:]
    spec = dict(R.STRUCTURES['M1'])
    spec['name'] = 'M1'
    x0, info0 = R.fit_structure(train, spec, p_base)
    assert x0 is not None and info0['supported'], info0
    clusters = [f"train_B:{w['cluster']}" for w in train]
    boot0 = R.bootstrap(train, spec, p_base, clusters, n=40, seed=R.BOOTSTRAP_SEED)
    hydro, G, _hv = R.expand_params(x0, spec, p_base)
    base = R.replay_all(hold, {'C': (hydro, G)})['C']

    bumped = []
    for w in hold:
        w2 = dict(w)
        w2['u'] = w['u'].copy()
        w2['u'][1:] = w2['u'][1:] + 0.10          # observation only
        bumped.append(w2)
    pert = R.replay_all(bumped, {'C': (hydro, G)})['C']
    assert any(abs(a['u'] - b['u']) > 1e-6 for a, b in zip(base, pert))

    x1, info1 = R.fit_structure(train, spec, p_base)
    boot1 = R.bootstrap(train, spec, p_base, clusters, n=40)
    assert np.allclose(x0, x1)
    assert boot0.get('intervals') is not None


def test_linear_interp_input_perturbation_changes_terms():
    p_base = R.old.load_baseline(os.path.join(
        os.path.dirname(os.path.dirname(os.path.dirname(HERE))),
        'usv_mpc_ws/src/usv_bringup/config/usv_params_B.yaml'))
    wins, _p, _s, t = _synthetic_windows(p_base, n=2)
    w = wins[0]
    snap_t = np.linspace(t[0], t[-1], 5)
    snap_l = np.linspace(1560.0, 1720.0, 5)          # ramp: ZOH != linear
    snap_r = np.linspace(1740.0, 1580.0, 5)
    z_s, z_d = R.input_terms(t, snap_t, snap_l, snap_r, mode='zoh')
    l_s, l_d = R.input_terms(t, snap_t, snap_l, snap_r, mode='linear')
    assert z_s > 0 and l_s > 0
    assert abs(z_s - l_s) / z_s > 1e-6
