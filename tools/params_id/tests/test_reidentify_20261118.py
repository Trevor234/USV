# ---------------------------------------------------------------------------
# 1. time base
# ---------------------------------------------------------------------------
def _time_base(n=400, dt_log=0.05, boot0=100.0):
    """ATTITUDE anchors with a +0.671 s backward log step at the half point."""
    boot = boot0 + dt_log * np.arange(n)
    log = boot + 1.0e6                      # constant Pi - FCU offset
    half = n // 2
    log[half:] -= 0.671                     # clock steps backwards
    seg, offs = R.clock_segments(log, boot)
    return R.TimeBase(log_s=log, boot_s=boot, ords=np.arange(n, dtype=float),
                      seg=seg, offs=offs)


def test_backward_clock_step_splits_segments():
    tb = _time_base()
    assert int(tb.seg.max()) == 1
    assert tb.offs[0] - tb.offs[1] == pytest.approx(0.671, abs=1e-6)
    # messages bracketed by file-order anchors still map inside the segment
    boot, seg = tb.boot_of(np.arange(10, 20, dtype=float), tb.log_s[10:20])
    assert np.isfinite(boot).all()
    assert np.allclose(boot, tb.boot_s[10:20], atol=1e-9)
    # a message exactly at the step is not interpolated across it
    mid = len(tb.log_s) // 2
    b, s = tb.boot_of([float(mid)], [tb.log_s[mid] - 1e-6])
    assert np.isfinite(b).all() and s[0] >= 0


def test_segment_local_epoch_keeps_phases_aligned():
    tb = _time_base()
    ep = tb.epoch_att()
    # every sample keeps its own segment offset: no global shift is applied
    assert np.allclose(ep - tb.boot_s, tb.offs[tb.seg])
    assert np.allclose(ep[tb.seg == 0] - tb.boot_s[tb.seg == 0], tb.offs[0])
    assert np.allclose(ep[tb.seg == 1] - tb.boot_s[tb.seg == 1], tb.offs[1])


def test_servo_unwrap_across_2_pow_32_and_gap():
    tb = _time_base(n=1200, dt_log=0.05, boot0=4290.0)  # spans the 2**32 us wrap
    # servo send times: 1 Hz, wrapping at 2**32 us, with a 2 s outage
    boot_true = 4292.0 + 1.0 * np.arange(40)
    drop = np.zeros(40, bool)
    drop[20:22] = True
    boot_true = boot_true[~drop]
    raw = np.mod(boot_true * 1e6, 2.0 ** 32)
    ords = np.searchsorted(tb.boot_s, boot_true).astype(float) + 0.5

    class P:
        servo = np.column_stack([tb.log_s[np.clip(ords.astype(int), 0, 1199)] * 1e9,
                                 raw, np.zeros(len(raw)),
                                 np.full(len(raw), 1600.0),
                                 np.full(len(raw), 1620.0), ords])
    est, valid, resid, k = R.servo_epoch(P, tb)
    assert k >= 1
    assert valid.sum() >= len(raw) - 2
    good = valid
    assert np.allclose(est[good], boot_true[good], atol=0.25)
    segs = R.servo_segments(est, valid)
    assert segs, "expected at least one contiguous servo segment"
    # the 2 s outage must break the stream: no segment may bridge it
    for s, e in segs:
        gaps = np.diff(est[s:e])
        assert np.all(gaps <= R.SERVO_GAP_S)


def test_gap_never_produces_a_window():
    tb = _time_base(n=1200, dt_log=0.05, boot0=4290.0)
    boot_true = 4292.0 + 1.0 * np.arange(40)
    drop = np.zeros(40, bool)
    drop[20:23] = True
    boot_true = boot_true[~drop]

    class P:
        servo = np.column_stack([
            tb.log_s[np.clip(np.searchsorted(tb.boot_s, boot_true), 0, 1199)] * 1e9,
            np.mod(boot_true * 1e6, 2.0 ** 32), np.zeros(len(boot_true)),
            np.full(len(boot_true), 1600.0), np.full(len(boot_true), 1620.0),
            np.searchsorted(tb.boot_s, boot_true).astype(float) + 0.5])
    est, valid, _r, _k = R.servo_epoch(P, tb)
    segs = R.servo_segments(est, valid)
    for s, e in segs:
        t = est[s:e]
        # every accepted segment is internally gap-free
        assert (np.diff(t) <= R.SERVO_GAP_S).all()
    # no 4 s window can be assembled across the removed snapshots
    gap_lo = boot_true[19]
    gap_hi = boot_true[20]
    for s, e in segs:
        t = est[s:e]
        straddles = (t[0] <= gap_lo) and (t[-1] >= gap_hi)
        assert not straddles


